//! Skills over MCP (`io.modelcontextprotocol/skills`) — progressive disclosure.
//!
//! The `cosmonic_*` tools are the hands; a **skill** is the manual. Without one,
//! a model faces 33 tools and has to infer the scaffold → build → publish →
//! apply → verify loop, the deny-all egress default, and the P2/P3 handler
//! distinction from tool descriptions alone. With one, it reads a playbook.
//!
//! Skills already ship as *installed* files — `~/.claude/skills/…` and the
//! per-agent equivalents, vendored per platform and kept current by
//! `src/main/agents.js`'s `autoUpdate()`. Serving them here means **connecting
//! to this server is enough**: every MCP client gets the playbook, including
//! the ones with no skills directory at all (LM Studio, NVIDIA OpenShell), and
//! an install that has gone stale is bypassed.
//!
//! ## The extension rides on `resources`
//!
//! There is no skills method in MCP — progressive disclosure is an extension
//! still in review (the current revision is 2026-07-28). So this uses the
//! **resources** primitive, which every client we support already speaks,
//! including ones still on 2025-06-18. Discovery is three tiers:
//!
//! 1. A client reads [`INDEX_URI`] (`skill://index.json`) once at session
//!    start: names plus the trigger descriptions it matches requests against.
//!    ~2 KB for the whole catalog.
//! 2. Only when a request matches does it read `skill://<name>/SKILL.md` —
//!    the playbook, tens of KB.
//! 3. Relative Markdown links inside a `SKILL.md` resolve against the skill
//!    root, so `[Templates](references/templates.md)` is
//!    `skill://<name>/references/templates.md`, pulled only at that depth.
//!
//! Reading all four playbooks and every reference would be ~276 KB. Reading the
//! index is ~2 KB. That gap is the entire point.
//!
//! ## Why `include_str!`
//!
//! The daemon runs as a service, with no dependency on the Electron app's
//! resource directory, and must work air-gapped. Embedding also makes drift
//! impossible: a playbook documenting a tool this binary does not have cannot
//! ship, because both come from the same build.
//!
//! ## Security
//!
//! [`read`] resolves a URI by matching it **verbatim** against the static
//! [`SKILLS`] table. There is no filesystem lookup, so there is no path
//! traversal to defend against — `skill://x/../../etc/passwd` simply matches
//! nothing and returns `None`. Keep it that way: if this ever reads from disk,
//! it needs a canonicalize-and-contain check first.
//!
//! ## Adding or updating a skill
//!
//! Don't edit `skills/` or the generated table by hand. `agent-integrations`
//! is the source of truth; run `node scripts/vendor-daemon-skills.mjs` and
//! commit the diff.

use rmcp::model::{Resource, ResourceTemplate};
