impl Skill {
    /// URI of this skill's `SKILL.md`.
    pub fn entry_uri(&self) -> String {
        format!("{SCHEME}{}/{ENTRY}", self.name)
    }

    /// URI of a supporting file.
    pub fn file_uri(&self, file: &SkillFile) -> String {
        format!("{SCHEME}{}/{}", self.name, file.path)
    }

    /// The `description` from the frontmatter — the trigger text a client
    /// matches user requests against.
    pub fn description(&self) -> &'static str {
        frontmatter_field(self.skill_md, "description").unwrap_or("")
    }
}

/// The skill catalog served at [`INDEX_URI`].
///
/// Built from [`SKILLS`] on every read rather than stored, so the catalog
/// cannot fall out of step with the embedded files.
pub fn index_json() -> String {
    let skills: Vec<_> = SKILLS
        .iter()
        .map(|skill| {
            json!({
                "name": skill.name,
                "description": skill.description(),
                "uri": skill.entry_uri(),
                "files": skill
                    .files
                    .iter()
                    .map(|file| json!({
                        "path": file.path,
                        "uri": skill.file_uri(file),
                        "mimeType": file.mime_type,
                    }))
                    .collect::<Vec<_>>(),
            })
        })
        .collect();

    let index = json!({
        "schemaVersion": "1",
        "extension": EXTENSION_ID,
        "server": {
            "name": "cosmonic-desktop",
            "version": env!("CARGO_PKG_VERSION"),
            "skillsVersion": SKILLS_VERSION,
        },
        "usage": "Read the SKILL.md of whichever skill's description matches the task, then only \
                  the reference files its body points you at. A playbook names those files by \
                  their path relative to the skill root (for example `references/recipes.md`, \
                  written as if on disk); read one here as skill://<skill>/<that path>. Every \
                  such path is listed under this skill's `files`.",
        "skills": skills,
    });
    // Built from &'static str and owned Vecs, so serialization cannot fail —
    // but never panic in the daemon over a resource read.
    serde_json::to_string_pretty(&index).unwrap_or_else(|_| String::from(r#"{"skills":[]}"#))
}

/// Every skill resource, for `resources/list`.
///
/// The index is listed with a description that tells a client to read it FIRST
/// and the playbooks only on a match — the whole catalog is otherwise just a
/// list of large files, and a client that reads them all has paid 276 KB for
/// what progressive disclosure exists to avoid.
pub fn resources() -> Vec<Resource> {
    let mut out = vec![Resource::new(INDEX_URI, "skill-index")
        .with_title("Skill catalog")
        .with_description(
            "Catalog of the skills this server publishes: name, trigger description, and the \
             URI of each SKILL.md. Read this first, then read only the skills whose \
             descriptions match the task.",
        )
        .with_mime_type("application/json")];

    for skill in SKILLS {
        out.push(
            Resource::new(skill.entry_uri(), skill.name)
                .with_title(format!("{} skill", skill.name))
                .with_description(format!(
                    "{}\n\nThis playbook names its supporting files by path relative to the \
                     skill root (e.g. `references/recipes.md`); read one as \
                     skill://{}/<that path>.",
                    skill.description(),
                    skill.name
                ))
                .with_mime_type("text/markdown")
                .with_size(clamp_size(skill.skill_md.len())),
        );
        for file in skill.files {
            out.push(
                Resource::new(
                    skill.file_uri(file),
                    format!("{}/{}", skill.name, file.path),
                )
                .with_title(format!("{} — {}", skill.name, file.path))
                .with_description(format!(
                    "Supporting file for the {} skill, linked from its SKILL.md.",
                    skill.name
                ))
                .with_mime_type(file.mime_type)
                .with_size(clamp_size(file.text.len())),
            );
        }
    }
    out
}

